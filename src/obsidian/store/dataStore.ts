// src/obsidian/store/dataStore.ts

import type {
  NoteJson,
  ParsedData,
  CombinedNoteData,
} from "../types/queryEngine";

/**
 * In-memory implementation of the data store.
 * Holds fetched NoteJson and parsed data (ParsedData) for efficient querying.
 */
export class DataStore {
  // The core data structure: Map<filePath, CombinedNoteData>
  private store = new Map<string, CombinedNoteData>();

  /**
   * Adds or updates the metadata (NoteJson) part of a note in the store.
   * If the note doesn't exist, it initializes it with empty ParsedData.
   * @param path - The file path (key).
   * @param noteJson - The NoteJson object from the API.
   */
  public addOrUpdateNoteMetadata(path: string, noteJson: NoteJson): void {
    console.log(`[DataStore] Adding/updating metadata for "${path}"`);
    console.log(`[DataStore] NoteJson structure:`, {
      hasContent: !!noteJson.content,
      contentLength: noteJson.content?.length || 0,
      hasFrontmatter: !!noteJson.frontmatter,
      frontmatterKeys: noteJson.frontmatter
        ? Object.keys(noteJson.frontmatter)
        : [],
      path: noteJson.path,
      hasStat: !!noteJson.stat,
      tags: noteJson.tags || [],
    });

    let existingEntry = this.store.get(path);

    if (existingEntry) {
      console.log(`[DataStore] Updating existing entry for "${path}"`);
      // Update only the NoteJson part
      existingEntry.note = noteJson;
    } else {
      console.log(`[DataStore] Creating new entry for "${path}"`);
      // Create a new entry with default ParsedData
      existingEntry = {
        note: noteJson,
        parsed: {
          // Initialize parsed data structure
          inlineFields: {},
          tasks: [],
        },
      };
    }
    this.store.set(path, existingEntry);
    console.log(`[DataStore] Current store size: ${this.store.size} notes`);
  }

  /**
   * Updates the parsed data part (ParsedData) for an existing note.
   * If the note doesn't exist, this method does nothing (metadata should be added first).
   * @param path - The file path (key).
   * @param parsedData - The ParsedData object generated by the ContentParser.
   */
  public addOrUpdateNoteParsedData(path: string, parsedData: ParsedData): void {
    console.log(`[DataStore] Adding/updating parsed data for "${path}"`);
    console.log(`[DataStore] ParsedData structure:`, {
      hasInlineFields: !!parsedData.inlineFields,
      inlineFieldCount: parsedData.inlineFields
        ? Object.keys(parsedData.inlineFields).length
        : 0,
      inlineFieldKeys: parsedData.inlineFields
        ? Object.keys(parsedData.inlineFields)
        : [],
      hasTaskData: !!parsedData.tasks,
      taskCount: parsedData.tasks?.length || 0,
    });

    const existingEntry = this.store.get(path);
    if (existingEntry) {
      console.log(`[DataStore] Found existing entry for "${path}"`);
      existingEntry.parsed = parsedData;
      this.store.set(path, existingEntry); // Re-set to ensure reactivity if needed later
    } else {
      console.warn(
        `[DataStore] WARNING: Tried to update parsed data for non-existent note: ${path}`
      );
    }
  }

  /**
   * Removes a note completely from the store.
   * @param path - The file path (key) of the note to remove.
   * @returns True if a note was removed, false otherwise.
   */
  public removeNote(path: string): boolean {
    console.log(`[DataStore] Removing note "${path}"`);
    const deleted = this.store.delete(path);
    console.log(
      `[DataStore] Note deletion ${deleted ? "successful" : "failed"}`
    );
    console.log(`[DataStore] Current store size: ${this.store.size} notes`);
    return deleted;
  }

  /**
   * Retrieves the combined data for a single note.
   * @param path - The file path (key).
   * @returns The CombinedNoteData object, or undefined if not found.
   */
  public getNote(path: string): CombinedNoteData | undefined {
    console.log(`[DataStore] Getting note data for "${path}"`);
    const note = this.store.get(path);
    console.log(`[DataStore] Note ${note ? "found" : "not found"}`);
    if (note) {
      console.log(`[DataStore] Note structure:`, {
        hasNoteData: !!note.note,
        hasParsedData: !!note.parsed,
        path: note.note.path,
        frontmatterKeys: note.note.frontmatter
          ? Object.keys(note.note.frontmatter)
          : [],
        tags: note.note.tags || [],
        inlineFieldKeys: note.parsed.inlineFields
          ? Object.keys(note.parsed.inlineFields)
          : [],
        taskCount: note.parsed.tasks?.length || 0,
      });
    }
    return note;
  }

  /**
   * Retrieves all notes currently in the store.
   * @returns An iterable iterator over all CombinedNoteData objects.
   */
  public getAllNotes(): IterableIterator<CombinedNoteData> {
    console.log(`[DataStore] Getting all notes (count: ${this.store.size})`);

    // Log information about the first few notes
    if (this.store.size > 0) {
      console.log(`[DataStore] Sample of notes in store:`);
      let count = 0;
      for (const [path, data] of this.store.entries()) {
        if (count < 3) {
          // Log details of up to 3 notes
          console.log(`[DataStore] Note ${count + 1}: "${path}"`, {
            hasContent: !!data.note.content,
            contentLength: data.note.content?.length || 0,
            hasFrontmatter: !!data.note.frontmatter,
            frontmatterKeys: data.note.frontmatter
              ? Object.keys(data.note.frontmatter)
              : [],
            tags: data.note.tags || [],
            fileName: path.split("/").pop(),
          });
        }
        count++;
      }
    } else {
      console.warn(
        `[DataStore] WARNING: getAllNotes called but store is empty!`
      );
    }

    return this.store.values();
  }

  /**
   * Get a debugging-friendly string representation of the store's contents.
   * @returns A string with details about the notes in the store.
   */
  public getStoreDebugInfo(): string {
    const notes = Array.from(this.store.entries());

    return (
      `DataStore contains ${notes.length} notes:\n` +
      notes
        .map(([path, data], index) => {
          return (
            `${index + 1}. "${path}": ` +
            `File name: "${path.split("/").pop()}", ` +
            `Tags: [${data.note.tags?.join(", ") || ""}], ` +
            `Content length: ${data.note.content?.length || 0}`
          );
        })
        .join("\n")
    );
  }

  /**
   * Retrieves a map of all known file paths to their last modification time (mtime).
   * Useful for checking against newly fetched data.
   * @returns A Map<filePath, mtime>.
   */
  public getAllMtimes(): Map<string, number> {
    console.log(`[DataStore] Getting all mtimes`);
    const mtimes = new Map<string, number>();
    for (const [path, combinedData] of this.store.entries()) {
      mtimes.set(path, combinedData.note.stat.mtime);
    }
    console.log(`[DataStore] Retrieved ${mtimes.size} mtimes`);
    return mtimes;
  }

  /**
   * Gets the total number of notes currently stored.
   * @returns The count of notes.
   */
  public getNoteCount(): number {
    console.log(`[DataStore] Getting note count: ${this.store.size}`);
    return this.store.size;
  }

  /**
   * Clears all data from the store.
   */
  public clearAll(): void {
    console.log(
      `[DataStore] Clearing all data (current size: ${this.store.size})`
    );
    this.store.clear();
    console.log(`[DataStore] Store cleared, new size: ${this.store.size}`);
  }

  /**
   * Get access to the internal store for the QueryEngine.
   * This is needed because QueryEngine needs direct access to the data.
   */
  public getInternalStore(): Map<string, CombinedNoteData> {
    console.log(
      `[DataStore] Getting internal store reference (size: ${this.store.size})`
    );
    return this.store;
  }

  // --- Methods required for Query Engine (will be used later) ---

  /**
   * Placeholder for a more advanced query method directly on the store.
   * For the in-memory version, the QueryEngine will likely just use getAllNotes()
   * and perform filtering/sorting itself. If we switch to IndexedDB, this method
   * would become more important for leveraging DB indexes.
   *
   * @param filterCriteria - The criteria to filter notes by.
   * @returns An array or iterable of matching CombinedNoteData.
   */
  public queryNotes(filterCriteria: any): CombinedNoteData[] {
    console.log(`[DataStore] queryNotes called with criteria:`, filterCriteria);
    console.warn(
      "[DataStore] queryNotes is basic; filtering happens in QueryEngine for in-memory store."
    );

    const notes = Array.from(this.store.values());
    console.log(
      `[DataStore] Returning ${notes.length} notes for query engine to filter`
    );

    if (notes.length > 0) {
      // Log a sample note structure to help with debugging
      console.log(`[DataStore] Sample note structure from queryNotes:`, {
        note: {
          path: notes[0].note.path,
          hasContent: !!notes[0].note.content,
          contentLength: notes[0].note.content?.length || 0,
          hasFrontmatter: !!notes[0].note.frontmatter,
          frontmatterKeys: notes[0].note.frontmatter
            ? Object.keys(notes[0].note.frontmatter)
            : [],
          hasStat: !!notes[0].note.stat,
          tags: notes[0].note.tags || [],
        },
        parsed: {
          hasInlineFields: !!notes[0].parsed.inlineFields,
          inlineFieldCount: notes[0].parsed.inlineFields
            ? Object.keys(notes[0].parsed.inlineFields).length
            : 0,
          hasTaskData: !!notes[0].parsed.tasks,
          taskCount: notes[0].parsed.tasks?.length || 0,
        },
      });
    }

    return notes;
  }
}
