import type { NoteJson, ParsedData, CombinedNoteData } from "../types";

/**
 * In-memory implementation of the data store.
 * Holds fetched NoteJson and parsed data (ParsedData) for efficient querying.
 */
export class DataStore {
  // The core data structure: Map<filePath, CombinedNoteData>
  private store = new Map<string, CombinedNoteData>();

  /**
   * Adds or updates the metadata (NoteJson) part of a note in the store.
   * If the note doesn't exist, it initializes it with empty ParsedData.
   * @param path - The file path (key).
   * @param noteJson - The NoteJson object from the API.
   */
  public addOrUpdateNoteMetadata(path: string, noteJson: NoteJson): void {
    let existingEntry = this.store.get(path);

    if (existingEntry) {
      // Update only the NoteJson part
      existingEntry.note = noteJson;
    } else {
      // Create a new entry with default ParsedData
      existingEntry = {
        note: noteJson,
        parsed: {
          // Initialize parsed data structure
          inlineFields: {},
          tasks: [],
        },
      };
    }
    this.store.set(path, existingEntry);
    // console.debug(`DataStore: Updated metadata for ${path}`);
  }

  /**
   * Updates the parsed data part (ParsedData) for an existing note.
   * If the note doesn't exist, this method does nothing (metadata should be added first).
   * @param path - The file path (key).
   * @param parsedData - The ParsedData object generated by the ContentParser.
   */
  public addOrUpdateNoteParsedData(path: string, parsedData: ParsedData): void {
    const existingEntry = this.store.get(path);
    if (existingEntry) {
      existingEntry.parsed = parsedData;
      this.store.set(path, existingEntry); // Re-set to ensure reactivity if needed later
      // console.debug(`DataStore: Updated parsed data for ${path}`);
    } else {
      console.warn(
        `DataStore: Tried to update parsed data for non-existent note: ${path}`
      );
    }
  }

  /**
   * Removes a note completely from the store.
   * @param path - The file path (key) of the note to remove.
   * @returns True if a note was removed, false otherwise.
   */
  public removeNote(path: string): boolean {
    const deleted = this.store.delete(path);
    if (deleted) {
      // console.debug(`DataStore: Removed note ${path}`);
    }
    return deleted;
  }

  /**
   * Retrieves the combined data for a single note.
   * @param path - The file path (key).
   * @returns The CombinedNoteData object, or undefined if not found.
   */
  public getNote(path: string): CombinedNoteData | undefined {
    return this.store.get(path);
  }

  /**
   * Retrieves all notes currently in the store.
   * @returns An iterable iterator over all CombinedNoteData objects.
   */
  public getAllNotes(): IterableIterator<CombinedNoteData> {
    return this.store.values();
  }

  /**
   * Retrieves a map of all known file paths to their last modification time (mtime).
   * Useful for checking against newly fetched data.
   * @returns A Map<filePath, mtime>.
   */
  public getAllMtimes(): Map<string, number> {
    const mtimes = new Map<string, number>();
    for (const [path, combinedData] of this.store.entries()) {
      mtimes.set(path, combinedData.note.stat.mtime);
    }
    return mtimes;
  }

  /**
   * Gets the total number of notes currently stored.
   * @returns The count of notes.
   */
  public getNoteCount(): number {
    return this.store.size;
  }

  /**
   * Clears all data from the store.
   */
  public clearAll(): void {
    this.store.clear();
    console.log("DataStore: Cleared all stored data.");
  }

  // --- Methods required for Query Engine (will be used later) ---

  /**
   * Placeholder for a more advanced query method directly on the store.
   * For the in-memory version, the QueryEngine will likely just use getAllNotes()
   * and perform filtering/sorting itself. If we switch to IndexedDB, this method
   * would become more important for leveraging DB indexes.
   *
   * @param filterCriteria - The criteria to filter notes by.
   * @returns An array or iterable of matching CombinedNoteData.
   */
  public queryNotes(filterCriteria: any): CombinedNoteData[] {
    // Basic implementation: return all and let QueryEngine filter
    // A more advanced in-memory version could do *some* pre-filtering here based on criteria
    console.warn(
      "DataStore.queryNotes is basic; filtering happens in QueryEngine for in-memory store."
    );
    return Array.from(this.store.values());
  }
}

