// src/obsidian/engine/queryParser.ts

import type {
  QueryRequest,
  QuerySource,
  FilterCriterion,
  SortCriterion,
} from "../types/queryEngine";

// Extend the QueryRequest type to include displayHeaders
// You'll need to add this to your types file or create a local extension
interface ExtendedQueryRequest extends QueryRequest {
  displayHeaders?: string[];
}

export class QueryParser {
  /**
   * Parse a DQL or DataviewJS string into a QueryRequest
   * @param queryString - The raw query string from the editor
   * @returns A structured QueryRequest object ready for the QueryEngine
   */
  parseQuery(queryString: string): QueryRequest {
    // Clean up the query string - remove code block markers
    const cleanQuery = this.cleanQueryString(queryString);

    // Detect if this is DataviewJS or standard DQL
    if (cleanQuery.trim().startsWith("dv.")) {
      return this.parseDataviewJS(cleanQuery);
    } else {
      return this.parseDQL(cleanQuery);
    }
  }

  /**
   * Clean up a query string by removing markdown code block syntax
   */
  private cleanQueryString(query: string): string {
    return query
      .replace(/```dataview\s*\n/g, "")
      .replace(/```dataviewjs\s*\n/g, "")
      .replace(/\n```$/g, "")
      .trim();
  }

  /**
   * Parse a standard Dataview DQL query string into a QueryRequest
   */
  private parseDQL(dqlString: string): QueryRequest {
    // Initial empty request with required properties
    const request: QueryRequest = {
      queryType: "TABLE", // Default
      sources: [],
      filters: [],
      sortBy: [],
      selectFields: [],
    };

    // Split the query into lines for easier parsing
    const lines = dqlString.split("\n").map((line) => line.trim());

    // Parse the first line to determine query type and fields
    const firstLine = lines[0] || "";

    // Check for query type
    if (firstLine.startsWith("TABLE")) {
      request.queryType = "TABLE";
      this.parseTableFields(firstLine, request);
    } else if (firstLine.startsWith("LIST")) {
      request.queryType = "LIST";
      // LIST has no fields to parse
    } else if (firstLine.startsWith("TASK")) {
      request.queryType = "TASK";
      // TASK has no fields to parse
    } else if (firstLine.startsWith("CALENDAR")) {
      request.queryType = "CALENDAR";
      this.parseCalendarField(firstLine, request);
    }

    // Parse the remaining lines
    for (let i = 1; i < lines.length; i++) {
      const line = lines[i];

      if (line.startsWith("FROM")) {
        this.parseFrom(line, request);
      } else if (line.startsWith("WHERE")) {
        this.parseWhere(line, request);
      } else if (line.startsWith("SORT")) {
        this.parseSort(line, request);
      } else if (line.startsWith("LIMIT")) {
        this.parseLimit(line, request);
      }
      // Ignore any other lines/clauses
    }

    return request;
  }

  /**
   * Parse a DataviewJS query string into a QueryRequest
   * This handles the specific pattern generated by the UI
   */
  private parseDataviewJS(jsString: string): QueryRequest {
    // Create default request structure
    const request: ExtendedQueryRequest = {
      queryType: "TABLE",
      sources: [],
      filters: [],
      sortBy: [],
      selectFields: [],
    };

    try {
      // Extract table headers
      const headersMatch = jsString.match(/dv\.table\((\[.*?\])/s);
      if (headersMatch && headersMatch[1]) {
        try {
          // Parse the headers array
          const headerArray = JSON.parse(headersMatch[1].replace(/'/g, '"'));

          // For DataviewJS, we'll store the display headers
          request.displayHeaders = headerArray;
        } catch (e) {
          console.warn("Failed to parse headers from DataviewJS:", e);
        }
      }

      // Extract the source (FROM)
      const sourceMatch = jsString.match(/dv\.pages\(\"(.*?)\"\)/);
      if (sourceMatch && sourceMatch[1]) {
        const sourcePath = sourceMatch[1];
        if (sourcePath) {
          request.sources.push({
            type: "FOLDER",
            value: sourcePath,
          });
        } else {
          // Empty string means all pages
          request.sources.push({
            type: "ALL",
            value: "",
          } as QuerySource); // Type assertion to handle 'value' property
        }
      } else {
        // Default to ALL if no source found
        request.sources.push({
          type: "ALL",
          value: "",
        } as QuerySource); // Type assertion
      }

      // Extract WHERE conditions
      const whereMatch = jsString.match(/\.where\(p\s*=>\s*(.*?)\)/);
      if (whereMatch && whereMatch[1]) {
        const whereClause = whereMatch[1];

        // Parse property conditions
        // Look for patterns like: p.status == "In Progress"
        const conditionMatch = whereClause.match(
          /p\.([^\s]+)\s*([=<>!]+|contains|includes)\s*(.+)/
        );
        if (conditionMatch) {
          const field = conditionMatch[1];
          let operator = conditionMatch[2];
          let value = conditionMatch[3];

          // Convert operator to the expected FilterCriterion operator type
          const mappedOperator = this.mapOperator(operator);

          // Clean up value - remove trailing parentheses etc.
          value = value.replace(/\)$/, "").trim();

          // Try to parse JSON values
          try {
            const parsedValue = JSON.parse(value);
            if (request.filters) {
              request.filters.push({
                field,
                operator: mappedOperator,
                value: parsedValue,
              });
            }
          } catch (e) {
            // If parsing fails, use the string directly
            if (request.filters) {
              request.filters.push({
                field,
                operator: mappedOperator,
                value,
              });
            }
          }
        }
      }

      // Extract SORT conditions
      const sortMatch = jsString.match(
        /\.sort\(p\s*=>\s*p\.([^,]+),\s*\"([^\"]+)\"\)/
      );
      if (sortMatch) {
        const field = sortMatch[1];
        const direction = sortMatch[2] as "asc" | "desc";

        if (request.sortBy) {
          request.sortBy.push({
            field,
            direction,
          });
        }
      }

      // Extract LIMIT
      const limitMatch = jsString.match(/\.limit\((\d+)\)/);
      if (limitMatch && limitMatch[1]) {
        request.limit = parseInt(limitMatch[1], 10);
      }

      // Extract field accessors from map function
      const mapMatch = jsString.match(/\.map\(p\s*=>\s*\[(.*?)\]\)/s);
      if (mapMatch && mapMatch[1]) {
        const accessors = mapMatch[1].split(",").map((a) => a.trim());

        // Convert accessors to field names
        if (request.selectFields) {
          request.selectFields = accessors.map((accessor) => {
            // Handle both forms:
            // p.field
            // p["field"]
            const dotMatch = accessor.match(/p\.([a-zA-Z0-9_.]+)/);
            if (dotMatch) return dotMatch[1];

            const bracketMatch = accessor.match(/p\[\"([^\"]+)\"\]/);
            if (bracketMatch) return bracketMatch[1];

            return accessor; // Return as is if no match
          });
        }
      }
    } catch (error) {
      console.error("Error parsing DataviewJS query:", error);
      // Return a minimal valid request if parsing fails
      return {
        queryType: "TABLE",
        sources: [{ type: "ALL", value: "" } as QuerySource], // Type assertion
        filters: [],
        sortBy: [],
        selectFields: ["file.name"],
      };
    }

    return request;
  }

  /**
   * Map string operators to valid FilterCriterion operators
   */
  private mapOperator(operator: string): FilterCriterion["operator"] {
    switch (operator) {
      case "=":
      case "==":
        return "==";
      case "!=":
        return "!=";
      case ">":
        return ">";
      case "<":
        return "<";
      case ">=":
        return ">=";
      case "<=":
        return "<=";
      case "contains":
        return "contains";
      case "includes":
        return "includes";
      // Add more mappings as needed
      default:
        console.warn(`Unsupported operator: ${operator}, defaulting to "=="`);
        return "==";
    }
  }

  /* Helper methods for DQL parsing */

  private parseTableFields(line: string, request: QueryRequest): void {
    // Handle "TABLE WITHOUT ID" syntax
    const withoutId = line.includes("WITHOUT ID");
    const fieldsStart =
      line.indexOf("TABLE") + 5 + (withoutId ? " WITHOUT ID".length : 0);

    // Get the field list part of the query
    const fieldsText = line.substring(fieldsStart).trim();
    if (!fieldsText) return; // No fields specified

    // Split fields by comma, but handle "AS" clauses carefully
    // This uses a regex that splits on commas not inside parentheses or quotes
    const fields = fieldsText
      .split(
        /,(?=(?:[^"]*"[^"]*")*[^"]*$)(?=(?:[^']*'[^']*')*[^']*$)(?=(?:[^(]*\([^)]*\))*[^(]*$)/
      )
      .map((f) => f.trim());

    if (request.selectFields) {
      request.selectFields = fields.map((field) => {
        // Handle "field AS alias" syntax
        const asMatch = field.match(
          /^(.+?)\s+AS\s+(?:"([^"]+)"|'([^']+)'|([^\s]+))$/i
        );
        if (asMatch) {
          // Return just the field part, not the alias
          return asMatch[1].trim();
        }
        return field;
      });
    }

    // Store display headers if "AS" was used
    const displayHeaders = fields.map((field) => {
      // Check if this field has an alias
      const asMatch = field.match(
        /^(.+?)\s+AS\s+(?:"([^"]+)"|'([^']+)'|([^\s]+))$/i
      );
      if (asMatch) {
        // Return the alias (could be in quotes or not)
        return asMatch[2] || asMatch[3] || asMatch[4];
      }
      // Otherwise the display header is the same as the field
      return field;
    });

    // Only set displayHeaders if they differ from selectFields
    if (
      request.selectFields &&
      displayHeaders.some((h, i) => {
        // Add this null check to ensure request.selectFields is defined inside the callback
        return request.selectFields && h !== request.selectFields[i];
      })
    ) {
      (request as ExtendedQueryRequest).displayHeaders = displayHeaders;
    }
  }

  private parseCalendarField(line: string, request: QueryRequest): void {
    // For CALENDAR queries, look for a field after CALENDAR
    const match = line.match(/^CALENDAR\s+(.+)$/i);
    if (match && match[1]) {
      request.calendarDateField = match[1].trim();
    }
  }

  private parseFrom(line: string, request: QueryRequest): void {
    const fromMatch = line.match(/^FROM\s+(.+)$/i);
    if (!fromMatch) return;

    const sourceText = fromMatch[1].trim();

    if (sourceText === '""' || sourceText === "''") {
      // Empty quotes mean all sources
      request.sources.push({
        type: "ALL",
        value: "",
      } as QuerySource); // Type assertion
    } else if (sourceText.startsWith("#")) {
      // Tag source
      request.sources.push({
        type: "TAG",
        value: sourceText.replace(/^#/, ""), // Remove leading # if present
      });
    } else if (sourceText.startsWith('"') || sourceText.startsWith("'")) {
      // Folder path - remove quotes
      const path = sourceText.replace(/^["']|["']$/g, "");
      request.sources.push({
        type: "FOLDER",
        value: path,
      });
    } else {
      // Assume it's a tag without #
      request.sources.push({
        type: "TAG",
        value: sourceText,
      });
    }
  }

  private parseWhere(line: string, request: QueryRequest): void {
    const whereMatch = line.match(/^WHERE\s+(.+)$/i);
    if (!whereMatch || !request.filters) return;

    const condition = whereMatch[1].trim();

    // Handle contains() function
    const containsMatch = condition.match(
      /contains\(([^,]+),\s*["']([^"']+)["']\)/i
    );
    if (containsMatch) {
      request.filters.push({
        field: containsMatch[1].trim(),
        operator: "contains",
        value: containsMatch[2],
      });
      return;
    }

    // Handle standard comparison operators
    const comparisonMatch = condition.match(
      /([^=!<>]+)\s*([=!<>]+|contains)\s*([^=!<>]+)/i
    );
    if (comparisonMatch) {
      const field = comparisonMatch[1].trim();
      const operator = this.mapOperator(comparisonMatch[2].trim());
      let value = comparisonMatch[3].trim();

      // Remove quotes from value if present
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }

      // Try to convert value to number if it looks like one
      const numValue = Number(value);
      const finalValue = !isNaN(numValue) ? numValue : value;

      request.filters.push({
        field,
        operator,
        value: finalValue,
      });
    }
  }

  private parseSort(line: string, request: QueryRequest): void {
    const sortMatch = line.match(/^SORT\s+(.+?)(?:\s+(ASC|DESC))?$/i);
    if (!sortMatch || !request.sortBy) return;

    const field = sortMatch[1].trim();
    const direction = (sortMatch[2]?.toLowerCase() || "asc") as "asc" | "desc";

    request.sortBy.push({
      field,
      direction,
    });
  }

  private parseLimit(line: string, request: QueryRequest): void {
    const limitMatch = line.match(/^LIMIT\s+(\d+)$/i);
    if (limitMatch) {
      request.limit = parseInt(limitMatch[1], 10);
    }
  }
}
